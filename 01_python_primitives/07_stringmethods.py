# ===========================================
# 1. upper()
# ===========================================

text = "python programming"
print(text.upper())          # PYTHON PROGRAMMING

# ===========================================
# 2. lower()
# ===========================================

text = "PYTHON PROGRAMMING"
print(text.lower())          # python programming

# ===========================================
# 3. capitalize()
# ===========================================

text = "python programming"
print(text.capitalize())     # Python programming

# ===========================================
# 4. title()
# ===========================================

text = "python programming language"
print(text.title())          # Python Programming Language

# ===========================================
# 5. swapcase()
# ===========================================

text = "Python Programming"
print(text.swapcase())       # pYTHON pROGRAMMING

# ===========================================
# 6. strip()
# ===========================================

text = "   Python   "
print(text.strip())          # Python

# ===========================================
# 7. lstrip()
# ===========================================

text = "   Python"
print(text.lstrip())         # Python

# ===========================================
# 8. rstrip()
# ===========================================

text = "Python   "
print(text.rstrip())         # Python

# ===========================================
# 9. replace()
# ===========================================

text = "I love Java"
print(text.replace("Java", "Python"))     # I love Python

# ===========================================
# 10. find()
# ===========================================

text = "Python Programming"

print(text.find("Program"))  # 7
print(text.find("Java"))     # -1

# ===========================================
# 11. index()
# ===========================================

text = "Python Programming"
print(text.index("Program")) # 7

# print(text.index("Java"))  # ValueError

# ===========================================
# 12. count()
# ===========================================

text = "banana"
print(text.count("a"))       # 3

# ===========================================
# 13. startswith()
# ===========================================

text = "Python Programming"
print(text.startswith("Python"))     # True

# ===========================================
# 14. endswith()
# ===========================================

text = "report.pdf"
print(text.endswith(".pdf"))         # True

# ===========================================
# 15. split()
# ===========================================

text = "Python Java C++"
print(text.split())          # ['Python', 'Java', 'C++']

# ===========================================
# 16. join()
# ===========================================

languages = ["Python", "Java", "C++"]
print(", ".join(languages))  # Python, Java, C++

# ===========================================
# 17. isalpha()
# ===========================================

text = "Python"
print(text.isalpha())        # True

# ===========================================
# 18. isdigit()
# ===========================================

text = "12345"
print(text.isdigit())        # True

# ===========================================
# 19. isalnum()
# ===========================================

text = "Python123"
print(text.isalnum())        # True

# ===========================================
# 20. islower()
# ===========================================

text = "python"
print(text.islower())        # True

# ===========================================
# 21. isupper()
# ===========================================

text = "PYTHON"
print(text.isupper())        # True

# ===========================================
# 22. istitle()
# ===========================================

text = "Python Programming"
print(text.istitle())        # True

# ===========================================
# 23. center()
# ===========================================

text = "Python"
print(text.center(20, "-"))  # -------Python-------

# ===========================================
# 24. ljust()
# ===========================================

text = "Python"
print(text.ljust(15, "-"))   # Python---------

# ===========================================
# 25. rjust()
# ===========================================

text = "Python"
print(text.rjust(15, "-"))   # ---------Python

# ===========================================
# 26. zfill()
# ===========================================

number = "25"
print(number.zfill(5))       # 00025

# ===========================================
# 27. casefold()
# ===========================================

text = "Python"
print(text.casefold())       # python

# ===========================================
# 28. partition()
# ===========================================

text = "Python-Programming"
print(text.partition("-"))   # ('Python', '-', 'Programming')

# ===========================================
# 29. rpartition()
# ===========================================

text = "one-two-three"
print(text.rpartition("-"))  # ('one-two', '-', 'three')

# ===========================================
# 30. encode()
# ===========================================

text = "Python"
print(text.encode())         # b'Python'