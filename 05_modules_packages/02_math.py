"""
===========================================
Python Math Module
===========================================

The math module provides useful mathematical
functions and constants.
"""

import math


# ===========================================
# 1. math.pi
# ===========================================

print(math.pi)                         # Pi value: 3.141592653589793


# ===========================================
# 2. math.e
# ===========================================

print(math.e)                          # Euler's number: 2.718281828459045


# ===========================================
# 3. math.sqrt()
# ===========================================

print(math.sqrt(25))                   # Calculates square root: 5.0


# ===========================================
# 4. math.pow()
# ===========================================

print(math.pow(2, 3))                  # Calculates 2 raised to power 3: 8.0


# ===========================================
# 5. math.ceil()
# ===========================================

print(math.ceil(4.2))                  # Rounds a number upward: 5


# ===========================================
# 6. math.floor()
# ===========================================

print(math.floor(4.8))                 # Rounds a number downward: 4


# ===========================================
# 7. math.factorial()
# ===========================================

print(math.factorial(5))               # Calculates factorial of 5: 120


# ===========================================
# 8. math.gcd()
# ===========================================

print(math.gcd(12, 18))                # Finds greatest common divisor: 6


# ===========================================
# 9. math.fabs()
# ===========================================

print(math.fabs(-10))                  # Returns positive absolute value: 10.0


# ===========================================
# 10. math.log()
# ===========================================

print(math.log(100, 10))               # Calculates logarithm of 100 with base 10: 2.0


